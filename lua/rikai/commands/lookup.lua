---@mod rikai-lookup
---@brief [[
---Lookup related utilities
---@brief ]]
local logger = require("rikai.log")
local api = vim.api

local M = {}

-- pasted
---@param name string
---@param value any
---@return integer|nil
function M.find_window_by_var(name, value)
	for _, win in ipairs(api.nvim_list_wins()) do
		if vim.w[win][name] == value then
			return win
		end
	end
end

---@class PopupLookupOpts
---

-- How to translate "日高" from our sqlite dbs ?
-- 1. first we tokenize
-- 2. For the first tokenized item
--    a. we detect if it's one kanji (one character) or an expression (several characters)
--    b.
---param args the arguments generated by mega.cmdparse
---@param token TokenizationResult
---@return number|nil winid
M.popup_lookup = function(token)
	logger:info("Looking into token: " .. token.surface)

	local normal_form = token.normal_form
	local focus_id = normal_form
	local bufnr = api.nvim_get_current_buf()

	-- here we reimplement part of open_floating_preview
	-- aka we want to check if we've
	local win = M.find_window_by_var(focus_id, bufnr)

	logger:debug(string.format("Looking for existing window with focus_id=%s", focus_id))
	---@diagnostic disable-next-line: unnecessary-if
	if win and api.nvim_win_is_valid(win) and vim.fn.pumvisible() == 0 then
		logger:debug(string.format("Found a window with focus_id=%s", focus_id))
		-- focus and return the existing buf, win
		api.nvim_set_current_win(win)
		api.nvim_command("stopinsert")
		return win
	else
		logger:debug(string.format("Could not find any preexisting popup focus_id=%s", focus_id))
	end

	-- the chosen token
	local formatted_results, details = require("rikai.lookup").format(token)
	if not formatted_results then
		print(details)
		return
	end
	logger:debug("Found " .. tostring(details.count) .. " results")

	--@type vim.lsp.util.open_floating_preview.Opts?
	local popupOpts = {
		-- focus existing popup with this id instead of creating one
		focusable = true,
		title = "rikai.nvim: " .. normal_form,
	}

	if details.count > 1 then
		popupOpts["title"] = popupOpts["title"] .. " (" .. tostring(details.count) .. " results)"
	end

	local winid = require("rikai.popup").create_popup(normal_form, formatted_results, popupOpts)
	return winid
end

return M
